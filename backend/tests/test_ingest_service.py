"""Tests for DataIngestService helpers and connection mention parsing."""
from unittest.mock import MagicMock

from app.services.chat.ingest import DataIngestService
from app.services.chat.pipeline import is_ingest_error_message


def _service() -> DataIngestService:
    return DataIngestService(MagicMock(), MagicMock())


def test_parse_connection_mention_api():
    svc = _service()
    conn_id, conn_type, sql_table = svc.parse_connection_mention(
        "@SalesAPI how many orders?",
        [],
        [{"id": "c1", "name": "SalesAPI"}],
    )
    assert conn_id == "c1"
    assert conn_type == "api"
    assert sql_table is None


def test_parse_connection_mention_sql_table():
    svc = _service()
    conn_id, conn_type, sql_table = svc.parse_connection_mention(
        "@WarehouseDB-orders total qty",
        [{"id": "db1", "name": "WarehouseDB"}],
        [],
    )
    assert conn_id == "db1"
    assert conn_type == "sql"
    assert sql_table == "orders"


def test_ingest_service_has_pipeline_helpers():
    svc = _service()
    assert hasattr(svc, "_emit_status")
    assert hasattr(svc, "_safe_chat_completion")
    assert callable(svc._engine_detail)


def test_is_ingest_error_message():
    assert is_ingest_error_message("Error: API connection not found.")
    assert is_ingest_error_message("Warning: The database contains no tables.")
    assert not is_ingest_error_message("Rows: 100 | Columns: 5")


def test_bytes_to_dataframe_detects_header_after_intro_rows():
    svc = _service()
    csv_bytes = (
        "Sales export,,\n"
        "Generated by POS,,\n"
        "region,amount\n"
        "North,100\n"
        "South,200\n"
    ).encode("utf-8")
    frame = svc._bytes_to_dataframe(csv_bytes, "sales.csv")
    assert frame is not None
    assert list(frame.columns) == ["region", "amount"]
    assert len(frame) == 2
